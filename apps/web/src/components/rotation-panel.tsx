"use client";

import { useCallback, useEffect, useState, type FormEvent } from "react";
import { BellRing, CalendarClock, Hand, Play, RefreshCw, Trash2, UserRound, Zap } from "lucide-react";
import { api, ApiError, type Member, type RotationExecution, type RotationPolicy, type RotationStrategy, type Secret } from "@/lib/api";
import { useApiError } from "@/components/org";
import {
  Badge,
  Button,
  Callout,
  Card,
  Drawer,
  EmptyState,
  Field,
  SkeletonRows,
  StatusBadge,
  ago,
  useConfirm,
  useToast,
  when,
} from "@/components/ui";

function days(list: string): number[] {
  return list
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean)
    .map(Number);
}

/**
 * Owner, rotation policy, rotate-now and rotation history for one secret.
 * Rotated values are generated by the provider and never pass through here.
 */
export function RotationPanel({
  base,
  secret,
  nativeAvailable,
  members,
  onChanged,
}: {
  base: string;
  secret: Secret;
  nativeAvailable: boolean;
  members: Member[];
  onChanged: () => void;
}) {
  const path = `${base}/secrets/${secret.id}`;
  const toast = useToast();
  const onError = useApiError();
  const { confirm, dialog } = useConfirm();
  const [state, setState] = useState<{ policy: RotationPolicy | null; history: RotationExecution[]; at: number } | null>(null);
  const [editing, setEditing] = useState(false);

  const load = useCallback(async () => {
    const [policy, h] = await Promise.all([
      api<RotationPolicy>("GET", `${path}/rotation-policy`).catch((e) => {
        if (e instanceof ApiError && e.code === "no_rotation_policy") return null;
        throw e;
      }),
      api<{ rotations: RotationExecution[] }>("GET", `${path}/rotations`),
    ]);
    return { policy, history: h.rotations, at: Date.now() };
  }, [path]);

  useEffect(() => {
    load().then(setState, onError);
  }, [load, onError]);

  // Poll while a rotation is running.
  const running = state?.history.some((h) => ["scheduled", "rotating", "verifying"].includes(h.status));
  useEffect(() => {
    if (!running) return;
    const t = setInterval(() => load().then(setState, () => {}), 3000);
    return () => clearInterval(t);
  }, [running, load]);

  async function act(action: () => Promise<unknown>, done: string) {
    try {
      await action();
      toast({ tone: "success", title: done });
      setState(await load());
      setEditing(false);
      onChanged();
    } catch (e) {
      onError(e);
    }
  }

  if (!state) {
    return (
      <Card>
        <SkeletonRows rows={3} />
      </Card>
    );
  }
  const { policy, history, at } = state;
  const overdue = policy?.enabled && Date.parse(policy.next_rotation_at) < at;

  return (
    <>
      <div className="grid-3">
        <Card
          title="Rotation policy"
          icon={
            <span className="cell-icon">
              <RefreshCw size={16} />
            </span>
          }
          description={policy ? (policy.strategy === "native" ? "Automatic, using the provider's rotation function" : "Manual, with reminders and escalation") : "Not configured"}
          actions={
            policy && (
              <>
                {policy.strategy === "native" && (
                  <Button
                    variant="primary"
                    size="sm"
                    icon={<Play size={14} />}
                    disabled={running}
                    onClick={() =>
                      confirm({
                        title: `Rotate ${secret.name} now?`,
                        body: "The provider's rotation function generates and applies a new value. Applications must be able to pick up the new version.",
                        action: "Rotate now",
                        run: () => act(() => api("POST", `${path}/rotate`), "Rotation started"),
                      })
                    }
                  >
                    {running ? "Rotating…" : "Rotate now"}
                  </Button>
                )}
                <Button size="sm" onClick={() => setEditing(true)}>
                  Edit
                </Button>
                <Button
                  size="sm"
                  variant="ghost"
                  icon={<Trash2 size={14} />}
                  aria-label="Remove policy"
                  onClick={() =>
                    confirm({
                      title: "Remove the rotation policy?",
                      body: "Scheduled rotations, reminders and escalations stop for this secret.",
                      action: "Remove",
                      danger: true,
                      run: () => act(() => api("DELETE", `${path}/rotation-policy`), "Rotation policy removed"),
                    })
                  }
                />
              </>
            )
          }
        >
          {!policy ? (
            <EmptyState
              icon={<CalendarClock size={22} />}
              title="No rotation policy"
              action={
                <Button variant="primary" onClick={() => setEditing(true)}>
                  Set up rotation
                </Button>
              }
            >
              Rotate automatically with the provider&apos;s rotation function, or get reminders and escalations for credentials people rotate.
            </EmptyState>
          ) : (
            <>
              {overdue && (
                <Callout tone="danger" title={`Overdue since ${when(policy.next_rotation_at)}`}>
                  {policy.strategy === "native"
                    ? "The last automatic rotation did not complete. Check the history below, or rotate now."
                    : "Rotate the credential and submit the new value with Change value."}
                </Callout>
              )}
              {!policy.enabled && <Callout tone="warning" title="Paused">No scheduled rotations or reminders while disabled.</Callout>}
              <dl className="kv">
                <dt>Every</dt>
                <dd>{policy.interval_days} days</dd>
                <dt>Next due</dt>
                <dd>
                  <span className={overdue ? "bad" : undefined}>{when(policy.next_rotation_at)}</span>{" "}
                  <span className="subtle">({ago(policy.next_rotation_at, at)})</span>
                </dd>
                <dt>Last rotated</dt>
                <dd>{secret.last_rotated_at ? when(secret.last_rotated_at) : "Never recorded"}</dd>
                {policy.strategy === "manual" && (
                  <>
                    <dt>Reminders</dt>
                    <dd>{policy.reminder_days.length ? `${policy.reminder_days.join(", ")} days before` : "None"}</dd>
                  </>
                )}
                <dt>Escalation</dt>
                <dd>
                  <EscalationSteps days={policy.escalation_days} />
                </dd>
              </dl>
            </>
          )}
        </Card>

        <Card
          title="Owner"
          icon={
            <span className="cell-icon">
              <UserRound size={16} />
            </span>
          }
          description="Gets reminders and is escalated to first"
        >
          <select
            className="select"
            value={secret.owner_user_id ?? ""}
            onChange={(e) =>
              act(() => api("PATCH", path, { owner_user_id: e.target.value || null }), e.target.value ? "Owner updated" : "Owner cleared")
            }
          >
            <option value="">No owner (all secret admins)</option>
            {members.map((m) => (
              <option key={m.user_id} value={m.user_id}>
                {m.email}
              </option>
            ))}
          </select>
          <span className="subtle" style={{ fontSize: 12.5 }}>
            The owner must be able to read this secret.
          </span>
        </Card>
      </div>

      <Card title="Rotation history" description={running ? "Updating live…" : "Automatic and on-demand rotations"} flush>
        {history.length === 0 ? (
          <EmptyState icon={<RefreshCw size={22} />} title="No rotations yet" />
        ) : (
          <table className="table">
            <thead>
              <tr>
                <th>Started</th>
                <th>Trigger</th>
                <th>Status</th>
                <th>New version</th>
              </tr>
            </thead>
            <tbody>
              {history.map((h) => (
                <tr key={h.id}>
                  <td title={when(h.created_at)}>{ago(h.created_at, at)}</td>
                  <td>
                    <Badge outline>{h.trigger === "schedule" ? "Scheduled" : "Rotate now"}</Badge>
                  </td>
                  <td>
                    <StatusBadge status={h.status} />
                    {h.error_code && <span className="bad" style={{ marginLeft: 8, fontSize: 12.5 }}>{h.error_code.replaceAll("_", " ")}</span>}
                  </td>
                  <td className="mono">{h.provider_version_id ?? "—"}</td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
      </Card>

      <Drawer
        open={editing}
        onClose={() => setEditing(false)}
        icon={<RefreshCw size={16} />}
        title={policy ? "Edit rotation policy" : "Set up rotation"}
        description="Needs a recent sign-in."
      >
        <PolicyForm
          initial={policy}
          nativeAvailable={nativeAvailable}
          onCancel={() => setEditing(false)}
          onSave={(body) => act(() => api("PUT", `${path}/rotation-policy`, body), "Rotation policy saved")}
        />
      </Drawer>
      {dialog}
    </>
  );
}

function EscalationSteps({ days: d }: { days: number[] }) {
  const who = ["owner", "+ security team", "+ org admins"];
  if (d.length === 0) return <span className="subtle">None</span>;
  return (
    <span style={{ display: "inline-flex", gap: 6, flexWrap: "wrap" }}>
      {d.map((n, i) => (
        <Badge key={i} tone={i === 0 ? "warning" : "danger"} outline>
          <BellRing size={11} /> +{n}d {who[i]}
        </Badge>
      ))}
    </span>
  );
}

function PolicyForm({
  initial,
  nativeAvailable,
  onSave,
  onCancel,
}: {
  initial: RotationPolicy | null;
  nativeAvailable: boolean;
  onSave: (body: Record<string, unknown>) => Promise<void>;
  onCancel: () => void;
}) {
  const [strategy, setStrategy] = useState<RotationStrategy>(initial?.strategy ?? (nativeAvailable ? "native" : "manual"));
  const [intervalDays, setIntervalDays] = useState(initial?.interval_days ?? 90);
  const [reminders, setReminders] = useState((initial?.reminder_days ?? [7, 3, 1]).join(", "));
  const [escalation, setEscalation] = useState((initial?.escalation_days ?? [1, 3, 7]).join(", "));
  const [enabled, setEnabled] = useState(initial?.enabled ?? true);
  const [busy, setBusy] = useState(false);

  async function submit(e: FormEvent) {
    e.preventDefault();
    setBusy(true);
    await onSave({ strategy, interval_days: intervalDays, reminder_days: days(reminders), escalation_days: days(escalation), enabled });
    setBusy(false);
  }

  return (
    <form className="form" onSubmit={submit}>
      <div className="field">
        <span className="label">Strategy</span>
        <div className="choice-grid">
          <button type="button" className="choice" aria-pressed={strategy === "native"} disabled={!nativeAvailable} onClick={() => setStrategy("native")}>
            <Zap size={18} color="var(--brand)" />
            <span>
              <strong>Automatic</strong>
              <small>The provider&apos;s rotation function generates and applies a new value on schedule.</small>
            </span>
          </button>
          <button type="button" className="choice" aria-pressed={strategy === "manual"} onClick={() => setStrategy("manual")}>
            <Hand size={18} color="var(--brand)" />
            <span>
              <strong>Manual</strong>
              <small>People rotate it; SecretMesh reminds and escalates until they do.</small>
            </span>
          </button>
        </div>
      </div>
      {strategy === "native" && (
        <Callout tone="info">
          The secret must already have a rotation function in the provider. SecretMesh decides when it runs and checks the result.
        </Callout>
      )}
      <Field label="Rotate every" hint="Counted from the last rotation." htmlFor="rp-interval">
        <div style={{ display: "flex", gap: 8, alignItems: "center" }}>
          <input id="rp-interval" className="input" type="number" min={1} max={3650} style={{ width: 110 }} value={intervalDays} onChange={(e) => setIntervalDays(Number(e.target.value))} />
          <span className="muted">days</span>
          <span style={{ display: "inline-flex", gap: 4, marginLeft: 8 }}>
            {[30, 90, 180, 365].map((d) => (
              <Button key={d} size="sm" variant={intervalDays === d ? "primary" : "secondary"} onClick={() => setIntervalDays(d)}>
                {d}d
              </Button>
            ))}
          </span>
        </div>
      </Field>
      {strategy === "manual" && (
        <Field label="Remind" hint="Days before the due date, comma separated." htmlFor="rp-rem">
          <input id="rp-rem" className="input" value={reminders} onChange={(e) => setReminders(e.target.value)} />
        </Field>
      )}
      <Field label="Escalate" hint="Days after the due date: first the owner, then also the security team, then also organization admins." htmlFor="rp-esc">
        <input id="rp-esc" className="input" value={escalation} onChange={(e) => setEscalation(e.target.value)} />
      </Field>
      <label className="check">
        <input type="checkbox" checked={enabled} onChange={(e) => setEnabled(e.target.checked)} />
        <span>Enabled</span>
      </label>
      <div style={{ display: "flex", gap: 8, justifyContent: "flex-end" }}>
        <Button onClick={onCancel}>Cancel</Button>
        <Button type="submit" variant="primary" loading={busy}>
          Save policy
        </Button>
      </div>
    </form>
  );
}
