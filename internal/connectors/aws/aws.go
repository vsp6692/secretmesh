// Package aws connects SecretMesh to AWS Secrets Manager.
//
// SecretMesh assumes a customer-owned IAM role with an ExternalId it
// generated (confused-deputy protection) and holds only short-lived STS
// credentials. Pending values are staged in the customer's account (ADR-0003):
//
//   - update: a new version labelled SECRETMESH_PENDING; AWSCURRENT stays on
//     the old version until promotion moves it.
//   - create: a shadow secret "secretmesh-staging/<request>"; promotion
//     creates the real secret from it.
//
// The execution journal ID is passed as ClientRequestToken, which makes
// creates idempotent and lets the reconciler find completed operations.
package aws

