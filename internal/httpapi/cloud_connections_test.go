package httpapi_test

import (
	"context"
	"net/http"
	"strings"
	"testing"
	"time"

	"github.com/Azure/azure-sdk-for-go/sdk/azcore"
	"github.com/Azure/azure-sdk-for-go/sdk/azcore/policy"
	"golang.org/x/oauth2"

	azureconn "github.com/secretmesh/secretmesh/internal/connectors/azure"
	gcpconn "github.com/secretmesh/secretmesh/internal/connectors/gcp"
	"github.com/secretmesh/secretmesh/internal/httpapi"
)

// staticAzureCredential stands in for SecretMesh's workload identity.
type staticAzureCredential struct{}

func (staticAzureCredential) GetToken(context.Context, policy.TokenRequestOptions) (azcore.AccessToken, error) {
	return azcore.AccessToken{Token: "test", ExpiresOn: time.Now().Add(time.Hour)}, nil
}

// Azure and GCP connections are created like AWS ones: SecretMesh generates
// the external ID, the settings are validated strictly, and credentials are
// never accepted.
func TestAzureAndGCPConnections(t *testing.T) {
	g := newGov(t)
	// Not registered by default (they are off unless enabled); no cloud is
	// called when a connection is created, so static identities suffice.
	az, err := azureconn.New(context.Background(), azureconn.Options{Credential: staticAzureCredential{}})
	if err != nil {
		t.Fatal(err)
	}
	g.registry.Register(azureconn.ProviderName, az.Factory)
	gc, err := gcpconn.New(context.Background(), gcpconn.Options{BaseTokenSource: oauth2.StaticTokenSource(&oauth2.Token{AccessToken: "test"})})
	if err != nil {
		t.Fatal(err)
	}
	g.registry.Register(gcpconn.ProviderName, gc.Factory)
	create := func(body map[string]any) response { return g.call(t, g.admin, "POST", g.o+"/connections", body) }

	azureCfg := map[string]string{"vault_url": "https://acme-prod.vault.azure.net", "tenant_id": "11111111-2222-3333-4444-555555555555"}
	gcpCfg := map[string]string{"project_id": "acme-prod-123456", "service_account": "secretmesh@acme-prod-123456.iam.gserviceaccount.com"}

	for _, tc := range []struct {
		provider string
		cfg      map[string]string
		bad      []map[string]string // each must be rejected
	}{
		{"azure", azureCfg, []map[string]string{
			{"vault_url": "http://acme-prod.vault.azure.net", "tenant_id": azureCfg["tenant_id"]},
			{"vault_url": "https://evil.example.com", "tenant_id": azureCfg["tenant_id"]},
			{"vault_url": azureCfg["vault_url"], "tenant_id": "not-a-guid"},
			{"vault_url": azureCfg["vault_url"], "tenant_id": azureCfg["tenant_id"], "client_secret": "x"},
			{"vault_url": azureCfg["vault_url"], "tenant_id": azureCfg["tenant_id"], "endpoint": "https://evil.example.com"},
			{"vault_url": azureCfg["vault_url"], "tenant_id": azureCfg["tenant_id"], "external_id": "secretmesh-chosen"},
		}},
		{"gcp", gcpCfg, []map[string]string{
			{"project_id": "Bad_Project", "service_account": gcpCfg["service_account"]},
			{"project_id": gcpCfg["project_id"], "service_account": "someone@example.com"},
			{"project_id": gcpCfg["project_id"]},
			{"project_id": gcpCfg["project_id"], "service_account": gcpCfg["service_account"], "private_key": "-----BEGIN"},
			{"project_id": gcpCfg["project_id"], "service_account": gcpCfg["service_account"], "external_id": "secretmesh-chosen"},
		}},
	} {
		t.Run(tc.provider, func(t *testing.T) {
			for i, cfg := range tc.bad {
				if r := create(map[string]any{"name": tc.provider + "-bad", "provider": tc.provider, "config": cfg}); r.Status != http.StatusBadRequest || r.code() != "invalid_config" {
					t.Errorf("bad config %d accepted: %d %s", i, r.Status, r.Body)
				}
			}
			r := create(map[string]any{"name": tc.provider + "-prod", "provider": tc.provider, "config": tc.cfg})
			if r.Status != http.StatusCreated {
				t.Fatalf("create: %d %s", r.Status, r.Body)
			}
			var conn httpapi.Connection
			r.decode(t, &conn)
			if !strings.HasPrefix(conn.Config["external_id"], "secretmesh-") || len(conn.Config["external_id"]) != len("secretmesh-")+32 {
				t.Errorf("external_id not generated by SecretMesh: %q", conn.Config["external_id"])
			}
			for k, v := range tc.cfg {
				if conn.Config[k] != v {
					t.Errorf("config %s = %q, want %q", k, conn.Config[k], v)
				}
			}
			if conn.Capabilities == nil || !conn.Capabilities.Discovery || !conn.Capabilities.SoftDelete || conn.Capabilities.NativeRotation {
				t.Errorf("capabilities: %+v", conn.Capabilities)
			}
		})
	}

}
